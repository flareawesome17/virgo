#!/usr/bin/env node
/**
 * Mints a signed URL for the media host.
 *
 * The media host serves nothing without a valid signature, which makes it
 * awkward to test by hand — this is the tool that makes it testable. It is
 * also the reference implementation: when the API starts minting these in
 * phase 2, it must produce byte-identical output for the same inputs, and
 * this file is what that gets checked against.
 *
 * The scheme, which has to match `secure_link_md5` in
 * deployment/media/nginx.conf.template exactly:
 *
 *   signature = base64url( md5( "<expires>/<key> <secret>" ) )
 *   url       = https://<host>/<expires>/<signature>/<key>
 *
 * The secret sits at the end of the digested string, not the start: md5 with
 * a leading secret is exposed to length extension, with a trailing one it is
 * not.
 *
 * Expiry is rounded DOWN to a window so that repeated signings inside the
 * same window return a byte-identical URL. That is what lets a browser reuse
 * what it already has instead of refetching every segment on every render —
 * the same reasoning as MEDIA_URL_WINDOW_SECONDS in
 * api/src/storage/storage.config.ts, and the same trade: real validity is
 * somewhere between `ttl - window` and `ttl`.
 *
 *   MEDIA_HOST=media.virgo.ph MEDIA_LINK_SECRET=… \
 *     node scripts/sign-media-url.mjs probe.txt
 *
 *   node scripts/sign-media-url.mjs users/a/albums/b/film-hls/master.m3u8 86400
 */
import { createHash } from 'node:crypto';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Matches PUBLISHED_URL_TTL_SECONDS — long enough that a film cannot expire mid-playback. */
const DEFAULT_TTL_SECONDS = 24 * 60 * 60;

/** Matches MEDIA_URL_WINDOW_SECONDS. */
const WINDOW_SECONDS = 5 * 60;

/**
 * Keys are generated by us, never taken from an uploaded filename, so they
 * stay inside this set. nginx matches its location against the *decoded*
 * URI, so anything needing percent-encoding would sign one string and be
 * verified against another.
 */
const SAFE_KEY = /^[A-Za-z0-9._\-/]+$/;

export function signMediaUrl(key, { host, secret, ttlSeconds = DEFAULT_TTL_SECONDS, now = Date.now() }) {
  if (!host) throw new Error('MEDIA_HOST is not set');
  if (!secret) throw new Error('MEDIA_LINK_SECRET is not set');

  const clean = key.replace(/^\/+/, '');
  if (!SAFE_KEY.test(clean)) {
    throw new Error(`Key contains characters that will not survive the round trip: ${key}`);
  }
  if (clean.includes('..')) throw new Error(`Key must not traverse: ${key}`);

  const expires =
    Math.floor((Math.floor(now / 1000) + ttlSeconds) / WINDOW_SECONDS) * WINDOW_SECONDS;

  const signature = createHash('md5')
    .update(`${expires}/${clean} ${secret}`)
    .digest('base64')
    // nginx's base64url: + → -, / → _, padding stripped.
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');

  return `https://${host}/${expires}/${signature}/${clean}`;
}

// Direct invocation only — importing this file must not run the CLI.
const invokedDirectly =
  process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  const [, , key, ttlArg] = process.argv;

  if (!key) {
    console.error('usage: node scripts/sign-media-url.mjs <key> [ttl-seconds]');
    process.exit(2);
  }

  try {
    const url = signMediaUrl(key, {
      host: process.env.MEDIA_HOST,
      secret: process.env.MEDIA_LINK_SECRET,
      ttlSeconds: ttlArg ? Number(ttlArg) : DEFAULT_TTL_SECONDS,
    });
    console.log(url);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
